import { useEffect, useMemo, useRef, useState } from 'react'
import { useSearchParams } from 'react-router-dom'
import EmptyState from '../../components/EmptyState'
import ErrorMessage from '../../components/ErrorMessage'
import Icon from '../../components/Icon'
import api from '../../services/api'
import useFetch from '../../hooks/useFetch'
import useServerCounts from '../../hooks/useServerCounts'
import AttendanceSheet from './Sheet'
import SessionHistory from './SessionHistory'
import SessionsBoard from './SessionsBoard'
import StatsCards from './StatsCards'
import StudentHistory from './StudentHistory'
import { EditSessionModal } from './dialogs'
import { ViewTabs } from './parts'
import { isoDay, shiftDay, statsQueries } from '../../utils/attendance'

/**
 * The teacher's attendance module.
 *
 * Three things are true here that were not when this screen read one flat list:
 * the dashboard figures come from the server's counts, the sessions view asks
 * for one day plus the next few, and the history asks for one page. A teacher
 * with four school years of registers therefore opens this screen as fast as a
 * teacher with four sessions — and the marks still save in one request.
 */
export default function TeacherAttendance({ assignmentId = null }) {
  const [searchParams] = useSearchParams()
  // My Classes hands over `?class=<assignment id>` so a teacher lands on the
  // class they just opened. Inside a class workspace the same id arrives as a
  // prop and cannot be changed: the activity is the class.
  const classLocked = assignmentId !== null && assignmentId !== undefined
  const initialClassId = classLocked
    ? String(assignmentId)
    : searchParams.get('class') || ''

  const [revision, setRevision] = useState(0)
  const [view, setView] = useState('sessions')
  const [historyTab, setHistoryTab] = useState('records')
  const [sheetFor, setSheetFor] = useState(null)
  const [sheetFrom, setSheetFrom] = useState('sessions')
  const [reviseFor, setReviseFor] = useState(null)
  const [generateError, setGenerateError] = useState(null)

  const assignments = useFetch('/teacher-assignments/', { list: true })
  const schedules = useFetch('/schedules/', { list: true })

  const refresh = () => setRevision((n) => n + 1)

  // Sessions are generated from the timetable on arrival, and the backend is
  // idempotent per (assignment, date, slot), so a second run writes nothing new.
  const autoGeneratedRef = useRef(false)
  useEffect(() => {
    if (schedules.loading || !schedules.data) return
    if (schedules.data.length === 0) return
    if (autoGeneratedRef.current) return
    autoGeneratedRef.current = true

    const today = isoDay()
    api
      .post('/attendance/generate/', { start_date: today, end_date: shiftDay(today, 7) })
      .then(refresh)
      .catch((err) => setGenerateError(err.message))
  }, [schedules.loading, schedules.data])

  const sectionId = useMemo(() => {
    const id = Number(initialClassId)
    if (!id) return ''
    const match = (assignments.data || []).find((a) => a.id === id)
    return match ? String(match.section) : ''
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [initialClassId, assignments.data])

  const stats = useServerCounts(
    statsQueries({ assignment: initialClassId, section: sectionId, today: isoDay() }),
    { refreshKey: revision }
  )

  function openSheet(session, from) {
    setSheetFrom(from)
    setSheetFor(session)
  }

  if (sheetFor) {
    const fromHistory = sheetFrom === 'history'
    return (
      <div className="stack stack-md">
        <AttendanceSheet
          key={sheetFor.id}
          session={sheetFor}
          onChanged={refresh}
          onBack={() => setSheetFor(null)}
          title={fromHistory ? 'Session details' : 'Take attendance'}
          backLabel={fromHistory ? 'History' : 'Attendance sessions'}
        />
      </div>
    )
  }

  const noSchedules = !schedules.loading && schedules.data && schedules.data.length === 0

  return (
    <div className="stack stack-md">
      {reviseFor && (
        <EditSessionModal
          session={reviseFor}
          onClose={() => setReviseFor(null)}
          onUpdated={refresh}
        />
      )}

      <StatsCards counts={stats.counts} loading={stats.loading} />

      {generateError && (
        <div className="alert alert-warning" role="alert">
          <Icon name="info" size={15} />
          <span>Could not generate today’s sessions: {generateError}</span>
        </div>
      )}

      {schedules.error && (
        <ErrorMessage
          error={schedules.error}
          title="Could not load your class schedules"
          onRetry={schedules.reload}
        />
      )}

      {stats.error && (
        <ErrorMessage error={stats.error} title="Could not load the summary figures" onRetry={stats.reload} />
      )}

      {noSchedules ? (
        <EmptyState
          icon="calendar"
          title="No class schedules configured"
          message="Ask your administrator to configure your class schedule. Attendance sessions are generated from your timetable."
        />
      ) : (
        <>
          <ViewTabs
            value={view}
            onChange={setView}
            label="Attendance view"
            tabs={[
              { id: 'sessions', label: 'Sessions' },
              { id: 'history', label: 'Attendance history' },
            ]}
          />

          {view === 'sessions' && (
            <div role="tabpanel" id="att-panel-sessions" aria-labelledby="att-tab-sessions">
              <SessionsBoard
                assignments={assignments.data || []}
                classLocked={classLocked}
                initialClassId={initialClassId}
                refreshKey={revision}
                onOpen={(session) => openSheet(session, 'sessions')}
              />
            </div>
          )}

          {view === 'history' && (
            <div
              role="tabpanel"
              id="att-panel-history"
              aria-labelledby="att-tab-history"
              className="stack stack-md"
            >
              <ViewTabs
                value={historyTab}
                onChange={setHistoryTab}
                label="Attendance history sections"
                tabs={[
                  { id: 'records', label: 'By session' },
                  { id: 'students', label: 'By student' },
                ]}
              />

              {historyTab === 'records' && (
                <div role="tabpanel" id="att-panel-records" aria-labelledby="att-tab-records">
                  <SessionHistory
                    assignments={assignments.data || []}
                    classLocked={classLocked}
                    initialClassId={initialClassId}
                    refreshKey={revision}
                    onOpen={(session) => openSheet(session, 'history')}
                    onRevise={setReviseFor}
                  />
                </div>
              )}

              {historyTab === 'students' && (
                <div role="tabpanel" id="att-panel-students" aria-labelledby="att-tab-students">
                  <StudentHistory refreshKey={revision} />
                </div>
              )}
            </div>
          )}
        </>
      )}
    </div>
  )
}
